// 개인정보 가리기 — 브라우저 안에서만 돈다. 원문은 어디에도 보내거나 저장하지 않는다.
// 이름 · 연락처 · 생년월일 · 전화번호 · 사번을 [이름] · [연락처] · [생년월일] · [전화번호] · [사번]으로 바꾼다.

export const MASK_TAGS = ['이름', '연락처', '생년월일', '전화번호', '사번'];

// 흔한 성씨. 낱말로 자주 쓰이는 글자(하 · 사 · 기 · 인 · 제 …)는 일부러 뺐다 — "사이즈예요"를 이름으로 잘못 가리지 않게.
const SURNAMES = '김이박최정강조윤장임한오서신권황안송류유전홍고문양손배백허남심노곽차주민지엄채변염추석설길진왕';
const S = `[${SURNAMES}]`;
// "라고 · 라 합니다" — 받침 있는 이름 뒤에서는 "이라고 · 이라 합니다"
const RA = '라(?:고|\\s*(?:합니다|해요|하고))';
// 이름 바로 뒤에 오는 말. "…이라고"는 앞의 '이'까지 이름으로 먹지 않게, 이름 끝 글자가 '이'면 "라고"를 받지 않는다 ("최종이라고")
const NAME_END = `(?:인데요|입니다|이에요|예요|이고|이요|님|씨|이${RA}|(?<!이)${RA})`;
// 자기소개 끝말 — NAME_END 에서 님 · 씨 · 이요를 뺀 것
const INTRO_END = `(?:인데요|입니다|이에요|예요|이고|이${RA}|(?<!이)${RA})`;
// 성 + 두 글자 꼴이지만 이름이 아닌 쇼핑몰 낱말 — 자기소개 자리에서도 가리지 않는다
const NOT_NAME = '(?!배송중|배송비|배송지|이번주|이번달|이번엔|주문중|주문건|정상가|정가로)';

// 만 14세 미만은 회원 가입에 법정대리인 동의가 필요하므로, 그보다 최근 연도의 날짜는 주문 날짜 등으로 보고 생년월일로 가리지 않는다.
const BIRTH_MAX_YEAR = new Date().getFullYear() - 14;

const RULES = [
  // 연락처: 이메일
  { tag: '연락처', re: /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g },
  // 연락처: 메신저 아이디 ("카톡 아이디 abc123")
  { tag: '연락처', keep: true,
    re: /((?:카톡|카카오톡|라인|텔레그램|인스타|메신저)\s*(?:아이디|ID|id|계정)?\s*(?:은|는|:|：)?\s*)([A-Za-z0-9_.]{3,})/g },
  // 사번 ("사번 A1234")
  { tag: '사번', keep: true,
    re: /((?:사번|사원번호|직원번호|임직원번호)\s*(?:은|는|이|:|：)?\s*)([A-Za-z]{0,3}-?\d{3,10})/g },
  // 생년월일: 앞에 "생년월일 · 생일 · 출생"이 있을 때
  { tag: '생년월일', keep: true,
    re: /((?:생년월일|생일|출생일?|생년)\s*(?:은|는|이|:|：)?\s*)(\d{8}|\d{6}|\d{2,4}\s*[.\-/년]\s*\d{1,2}\s*[.\-/월]\s*\d{1,2}(?:\s*일)?)/g },
  // 생년월일: 연도까지 있는 날짜 (BIRTH_MAX_YEAR 이하만)
  { tag: '생년월일', yearCheck: true,
    re: /(?<!\d)((?:19|20)\d{2})\s*[.\-/년]\s*(?:0?[1-9]|1[0-2])\s*[.\-/월]\s*(?:0?[1-9]|[12]\d|3[01])(?:\s*일)?(?!\d)/g },
  // 전화번호: 010-1234-5678, 02 123 4567, 01012345678, +82 10-…
  { tag: '전화번호',
    re: /(?<!\d)(?:\+82[-.\s]?0?|0)\d{1,2}[-.\s)]?\d{3,4}[-.\s]?\d{4}(?!\d)/g },
  // 이름: 앞에 "이름 · 성함 · 입금자명 · 주문자 · 수령인 …"이 있고, 띄어쓰기나 "은 · 는 · :"로 떨어져 있을 때
  //       ("이름이랑"의 '이랑'을 이름으로 잘못 가리지 않게)
  { tag: '이름', keep: true,
    re: new RegExp(`((?:이름|성함|입금자명|입금자|주문자명|주문자|수령인|수취인|예금주|받는\\s?분|받는\\s?사람)(?:\\s*(?:은|는|:|：)\\s*|\\s+))(${S}[가-힣]{1,3}?)(?=${NAME_END}|[^가-힣]|$)`, 'g') },
  // 이름: 자기소개 자리에서 성 + 두 글자 + "인데요 · 입니다 · 라고 합니다 …" ("박지은인데요", "나는 김인수라 합니다")
  //       자기소개 자리 = 문장 맨 앞, 문장부호나 다른 가림 표시 뒤, "나는 · 저는" 바로 뒤
  //       문장 가운데 아무 데나 보면 "배송중이에요"를 이름으로 잘못 가리므로 자리를 좁혔다
  { tag: '이름',
    re: new RegExp(`(?<=(?:^|[.!?,~\\n\\]])\\s*(?:(?:나는|저는)\\s+)?)${NOT_NAME}${S}[가-힣]{2}(?=${INTRO_END})`, 'g') },
  // 이름: 어디서든 성 + 두 글자 + "님 · 씨" ("김철수님")
  { tag: '이름',
    re: new RegExp(`(?<![가-힣])${S}[가-힣]{2}(?=님|씨)`, 'g') },
];

export function maskText(input) {
  let text = String(input ?? '');
  const found = {};
  for (const rule of RULES) {
    text = text.replace(rule.re, (...m) => {
      if (rule.yearCheck && Number(m[1]) > BIRTH_MAX_YEAR) return m[0];
      found[rule.tag] = (found[rule.tag] || 0) + 1;
      return rule.keep ? `${m[1]}[${rule.tag}]` : `[${rule.tag}]`;
    });
  }
  return { text, found };
}
