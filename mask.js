// 개인정보 가리기 — 브라우저 안에서만 돈다. 원문은 어디에도 보내거나 저장하지 않는다.
// 이름 · 연락처 · 생년월일 · 전화번호 · 사번을 [이름] · [연락처] · [생년월일] · [전화번호] · [사번]으로 바꾼다.

export const MASK_TAGS = ['이름', '연락처', '생년월일', '전화번호', '사번'];

// 흔한 성씨. 낱말로 자주 쓰이는 글자(하 · 사 · 기 · 인 · 제 …)는 일부러 뺐다 — "사이즈예요"를 이름으로 잘못 가리지 않게.
const SURNAMES = '김이박최정강조윤장임한오서신권황안송류유전홍고문양손배백허남심노곽차주민지엄채변염추석설길진왕';
const S = `[${SURNAMES}]`;
// 두 글자 성
const COMPOUND = '(?:남궁|황보|제갈|선우|독고|사공|서문|동방)';
// 이름은 성까지 다섯 글자까지 잡는다 (두 글자 성 + 1~3글자, 한 글자 성 + 1~4글자)
const NAME_LAZY = `(?:${COMPOUND}[가-힣]{1,3}?|${S}[가-힣]{1,4}?)`;
// 이름표 없이 잡을 때는 성 + 두 글자 이상 (세~다섯 글자) — "고객님" 같은 두 글자 낱말을 가리지 않게
const NAME_3TO5 = `(?:${COMPOUND}[가-힣]{1,3}|${S}[가-힣]{2,4})`;
// 직급 — 이 앞의 낱말은 성이 목록에 없어도 이름으로 본다 ("테스트이름 사원")
//        "이사"는 "집 이사"와 헷갈려서 뺐다. "대리 수령 · 대리 결제"의 대리는 직급이 아니다
const TITLE = '(?:사원|주임|대리(?!\\s?(?:수령|결제|구매|주문|접수))|과장|차장|부장|팀장|실장|본부장|매니저)';
// 직급 뒤에 올 수 있는 말 (없거나, 님 · 입니다 · 께 · 에게 …)
const AFTER_TITLE = '님?(?:(?![가-힣])|입니다|인데요|이에요|이세요|이고|이|은|을|께서?|에게|한테|이랑|하고|도|의)';
// 이름 자리에 왔지만 이름이 아닌 낱말 — 앞이나 끝이 이렇게 생겼으면 가리지 않는다
//   앞: 쇼핑몰 · 회사 낱말 ("주문번호예요", "배송기사님", "우리 팀장님")
//   끝: 부서 · 사람을 가리키는 낱말, 또는 조사 "가 · 는 · 를 …" ("광고가 과장이에요")
const NOT_NAME_WORD = /^(?:우리|저희|담당|해당|다른|어느|어떤|직원|본인|고객|배송|주문|택배|영업|물류|경비|교환|환불|반품|결제|취소)|(?:팀|센터|지점|본부|매장|부서|회사|기사|고객|직원|사장|선생|회원|담당자?|상담원|점장|경비실|관리실|[가는를을도에의와])$/;
// 조사를 떼면 이 낱말과 똑같은 것 ("이름 변경하고", "주문자 정보랑") — 앞만 같은 "정보람"은 이름일 수 있어 그대로 둔다
const NOT_NAME_EXACT = /^(?:변경|정보|수정|정정|확인|주소|번호|문의|연락처|전화|입력|등록|조회)(?:하고|해서|해|이랑|랑|이|가|은|는|을|를|도|좀)?$/;
const notName = (word) => NOT_NAME_WORD.test(word) || NOT_NAME_EXACT.test(word);
// "라고 · 라 합니다" — 받침 있는 이름 뒤에서는 "이라고 · 이라 합니다"
const RA = '라(?:고|\\s*(?:합니다|해요|하고))';
// 이름 바로 뒤에 오는 말. "…이라고"는 앞의 '이'까지 이름으로 먹지 않게, 이름 끝 글자가 '이'면 "라고"를 받지 않는다 ("최종이라고")
const NAME_END = `(?:인데요|입니다|이에요|예요|이고|이요|님|씨|이${RA}|(?<!이)${RA})`;
// 자기소개 끝말 — NAME_END 에서 님 · 씨 · 이요를 뺀 것
const INTRO_END = `(?:인데요|입니다|이에요|예요|이고|이${RA}|(?<!이)${RA})`;
// 성 + 두 글자 꼴이지만 이름이 아닌 쇼핑몰 낱말 — 자기소개 자리에서도 가리지 않는다
const NOT_NAME = '(?!배송중|배송비|배송지|이번주|이번달|이번엔|주문중|주문건|정상가|정가로)';

// 만 14세 미만은 회원 가입에 법정대리인 동의가 필요하므로, 그보다 최근 연도의 날짜는 주문 날짜 등으로 보고 생년월일로 가리지 않는다.
const BIRTH_MAX_YEAR = new Date().getFullYear() - 14;

const RULES = [
  // 연락처: 이메일
  { tag: '연락처', re: /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g },
  // 연락처: 메신저 아이디 ("카톡 아이디 abc123")
  { tag: '연락처', keep: true,
    re: /((?:카톡|카카오톡|라인|텔레그램|인스타|메신저)\s*(?:아이디|ID|id|계정)?\s*(?:은|는|:|：)?\s*)([A-Za-z0-9_.]{3,})/g },
  // 사번 ("사번 A1234")
  { tag: '사번', keep: true,
    re: /((?:사번|사원번호|직원번호|임직원번호)\s*(?:은|는|이|:|：)?\s*)([A-Za-z]{0,3}-?\d{3,10})/g },
  // 생년월일: 앞에 "생년월일 · 생일 · 출생"이 있을 때
  { tag: '생년월일', keep: true,
    re: /((?:생년월일|생일|출생일?|생년)\s*(?:은|는|이|:|：)?\s*)(\d{8}|\d{6}|\d{2,4}\s*[.\-/년]\s*\d{1,2}\s*[.\-/월]\s*\d{1,2}(?:\s*일)?)/g },
  // 생년월일: 연도까지 있는 날짜 (BIRTH_MAX_YEAR 이하만)
  { tag: '생년월일', yearCheck: true,
    re: /(?<!\d)((?:19|20)\d{2})\s*[.\-/년]\s*(?:0?[1-9]|1[0-2])\s*[.\-/월]\s*(?:0?[1-9]|[12]\d|3[01])(?:\s*일)?(?!\d)/g },
  // 전화번호: 010-1234-5678, 02 123 4567, 01012345678, +82 10-…
  { tag: '전화번호',
    re: /(?<!\d)(?:\+82[-.\s]?0?|0)\d{1,2}[-.\s)]?\d{3,4}[-.\s]?\d{4}(?!\d)/g },
  // 이름: 앞에 "이름 · 성함 · 입금자명 · 주문자 · 수령인 …"이 있고, 띄어쓰기나 "은 · 는 · :"로 떨어져 있을 때
  //       ("이름이랑"의 '이랑'을 이름으로 잘못 가리지 않게)
  { tag: '이름', keep: true, skip: notName,
    re: new RegExp(`((?:이름|성함|입금자명|입금자|주문자명|주문자|수령인|수취인|예금주|받는\\s?분|받는\\s?사람)(?:\\s*(?:은|는|:|：)\\s*|\\s+))(${NAME_LAZY})(?=${NAME_END}|(?:으로|로|가|은|는|을|를|와|과|에게|한테|께|앞|이랑|랑)?(?:[^가-힣]|$))`, 'g') },
  // 이름: 자기소개 자리에서 성 + 두~네 글자 + "인데요 · 입니다 · 라고 합니다 …" ("박지은인데요", "나는 김인수라 합니다")
  //       자기소개 자리 = 문장 맨 앞, 문장부호나 다른 가림 표시 뒤, "나는 · 저는" 바로 뒤
  //       문장 가운데 아무 데나 보면 "배송중이에요"를 이름으로 잘못 가리므로 자리를 좁혔다
  { tag: '이름', skip: notName,
    re: new RegExp(`(?<=(?:^|[.!?,~\\n\\]])\\s*(?:(?:나는|저는)\\s+)?)${NOT_NAME}${NAME_3TO5}(?=${INTRO_END})`, 'g') },
  // 이름: 두~다섯 글자 + 직급 ("테스트이름 사원", "김철수 대리님") — 직급이 있으면 성이 목록에 없어도 잡는다
  { tag: '이름', skip: notName,
    re: new RegExp(`(?<![가-힣])[가-힣]{2,5}(?=\\s?${TITLE}${AFTER_TITLE})`, 'g') },
  // 이름: 어디서든 성 + 두~네 글자 + "님 · 씨" ("김철수님", "남궁민수씨")
  { tag: '이름', skip: notName,
    re: new RegExp(`(?<![가-힣])${NAME_3TO5}(?=님|씨)`, 'g') },
];

export function maskText(input) {
  let text = String(input ?? '');
  const found = {};
  for (const rule of RULES) {
    text = text.replace(rule.re, (...m) => {
      if (rule.yearCheck && Number(m[1]) > BIRTH_MAX_YEAR) return m[0];
      if (rule.skip && rule.skip(rule.keep ? m[2] : m[0])) return m[0]; // 이름 자리의 낱말만 본다
      found[rule.tag] = (found[rule.tag] || 0) + 1;
      return rule.keep ? `${m[1]}[${rule.tag}]` : `[${rule.tag}]`;
    });
  }
  return { text, found };
}
